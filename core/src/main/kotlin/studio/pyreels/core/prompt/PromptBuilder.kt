package studio.pyreels.core.prompt

import studio.pyreels.core.Resources
import studio.pyreels.core.brief.Brief
import studio.pyreels.core.brief.EpisodeRecord
import studio.pyreels.core.brief.SeriesMemory
import studio.pyreels.core.content.ContentRepository
import studio.pyreels.core.content.CurriculumLesson
import studio.pyreels.core.model.AmbientMoods
import studio.pyreels.core.model.Limits
import studio.pyreels.core.model.Personas
import studio.pyreels.core.model.SfxIds
import studio.pyreels.core.validate.Problem
import java.time.LocalDate

/**
 * Builds the engineered Markdown prompt (section 6 of the brief) that any strong AI can follow to
 * write a scenario that fits the app exactly. Sections appear in the mandated order 1–12.
 */
object PromptBuilder {

    data class Input(
        val brief: Brief,
        val history: List<EpisodeRecord> = emptyList(),
        /** Lessons of a weekly plan (null = single episode). */
        val weekly: List<CurriculumLesson>? = null,
    )

    fun fileName(brief: Brief, date: LocalDate = LocalDate.now(), weekly: Boolean = false): String {
        val lesson = (brief.lessonId ?: brief.lessonTitle.ifBlank { "lesson" })
            .lowercase().replace(Regex("[^a-z0-9\\u0600-\\u06FF-]+"), "-").trim('-').ifBlank { "lesson" }
        return if (weekly) "prompt_weekly_${lesson}_$date.md" else "prompt_${lesson}_$date.md"
    }

    fun build(input: Input): String {
        val b = input.brief.normalized()
        val curriculum = ContentRepository.curriculum
        val lesson = curriculum.byId(b.lessonId)
        val topic = lesson?.title ?: b.lessonTitle.ifBlank { "درس اليوم" }
        val sb = StringBuilder()
        fun h(n: Int, title: String) = sb.append("\n## $n. $title\n\n")

        sb.append("# برومبت احترافي — سيناريو فيديو PyReels Studio\n\n")
        sb.append("> Generated by PyReels Studio. Schema `pyreels/1`. Topic: **$topic**")
        input.weekly?.let { sb.append(" — Weekly plan: ${it.size} episodes") }
        sb.append("\n")

        // 1
        h(1, "Role and goal")
        sb.append(
            """You are a **senior instructional scriptwriter for Arabic programming-education short videos** (TikTok / Instagram Reels, vertical 9:16).
Your goal: write ${if (input.weekly != null) "a JSON **array of ${input.weekly.size} linked scenarios**" else "**one scenario file**"} that the PyReels Studio app renders directly into a calm, polished ~${b.targetSeconds}-second lesson video.
The video is a WhatsApp-style group chat between **Ahmed (أحمد), a beginner learner**, and programming languages as teacher characters, plus an in-video code editor and terminal.
The viewer must feel: "my questions are normal, I'm learning with Ahmed, and I want the next episode."
""",
        )

        // 2
        h(2, "App and tool manifest (what the app can render)")
        sb.append("Scene types (the ONLY ones allowed):\n\n")
        sb.append("| type | purpose | required fields | optional fields |\n|---|---|---|---|\n")
        sceneTable.forEach { (t, p, r, o) -> sb.append("| `$t` | $p | $r | $o |\n") }
        sb.append(
            """
Common optional fields on every scene: `say` (boolean, read aloud by TTS), `sfx` (one SFX id), `spoken` (explicit spoken text), `speakCode` (boolean), `transition` (`fade` | `slide` | `zoom`), `durationMs` (normally omit; the engine computes durations).

- **Allowed SFX ids:** ${SfxIds.ALL.joinToString(", ") { "`$it`" }}. Default sounds are automatic; only set `sfx` to override.
- **Ambient moods (meta.ambient):** ${AmbientMoods.ALL.joinToString(", ") { "`$it`" }}.
- **Themes (meta.theme):** `calm-dark`, `calm-light`. Use `${b.theme}`.
- **Cast ids:** `ahmed` (role `learner`, always present) + teacher ids: ${b.teachers.joinToString(", ") { "`$it`" }} (role `teacher`, field `language` = same id).
- **Code languages:** python, java, cpp, javascript, kotlin, csharp, go, rust, php, typescript, swift, c.
- Python `run` scenes may use `"exec": "real"` (executed in a sandbox; the trace is derived from real execution). Every other language MUST use `"exec": "simulated"` with a correct `output` and `trace`.

**Limits (hard):**
- Chat bubble: max ${Limits.MAX_CHARS_PER_LINE} characters per line, max ${Limits.MAX_LINES_PER_BUBBLE} lines (≈ ${Limits.MAX_BUBBLE_CHARS} characters). Prefer 1–2 short lines readable in 2–3 seconds.
- Reading speed budget: ≤ ${Limits.WORDS_PER_SECOND} Arabic words per second.
- Code: max ${Limits.MAX_CODE_LINES} lines, max ${Limits.MAX_CODE_LINE_CHARS} characters per line; `trace` max 16 steps, max 6 variables per step; output max ${Limits.MAX_OUTPUT_LINES} lines.
- Sentence of the day (`key_sentence`): ≤ ${Limits.MAX_KEY_SENTENCE_WORDS} words.
- Scene durations: ${Limits.MIN_SCENE_MS / 1000.0}–${Limits.MAX_SCENE_MS / 1000} s each; the hook is exactly 3 s. No static scene longer than 6 s.
- Total duration target ${b.targetSeconds} s (± 10 %), warning above ${Limits.WARN_SECONDS} s, impossible above ${Limits.HARD_CAP_SECONDS} s. Typical size: 22–32 scenes.
- Cast: Ahmed + 1–4 teachers. Scenes: 6–60.

**Impossible (never request):** images, photos, video clips, external audio, music, links, GIFs, emojis inside code, new scene types, new SFX ids, games, flashing or shaking effects.
""",
        )

        // 3
        h(3, "The creator's brief")
        sb.append("```yaml\n")
        sb.append("teachers: ${b.teachers}\n")
        sb.append("lesson_id: ${b.lessonId ?: "custom"}\n")
        sb.append("lesson_title: \"$topic\"\n")
        sb.append("concept: ${lesson?.concept ?: "(one concept chosen from the title)"}\n")
        sb.append("learner_level: ${b.level}\n")
        sb.append("example: ${if (b.exampleMode == "custom" && b.customExample.isNotBlank()) "custom" else "auto"}\n")
        sb.append("teaching_methods: ${b.methods}\n")
        sb.append("tone: ${b.tone}\nhumor_level: ${b.humor}/5\n")
        sb.append("language_style: ${b.languageStyle}\n")
        sb.append("include_common_mistake: ${b.includeMistake}\ninclude_challenge: ${b.includeChallenge}\n")
        sb.append("voice_over: ${b.voiceOver}\ntarget_seconds: ${b.targetSeconds}\ntheme: ${b.theme}\n")
        sb.append("```\n\n")
        sb.append("**Summary:** درس عن «$topic» لمستوى ${Brief.LEVELS[b.level] ?: b.level}، بأسلوب ${Brief.TONES[b.tone] ?: b.tone} (مستوى المزاح ${b.humor}/5)، ")
        sb.append("بطريقة: ${b.methods.joinToString("، ") { Brief.METHODS[it] ?: it }}. اللغة: ${Brief.STYLES[b.languageStyle] ?: b.languageStyle}. ")
        sb.append("المعلّمون: ${b.teachers.joinToString("، ") { Personas.forLanguage(it).nameAr }}.\n")
        lesson?.let {
            sb.append("\nRoadmap data for this lesson (use it, improve wording freely):\n")
            sb.append("- summary: ${it.summary}\n- analogy idea: ${it.analogy}\n- key sentence idea: ${it.keySentence}\n")
            sb.append("- example code (verified):\n```python\n${it.example}\n```\n- its real output:\n```\n${it.expectedOutput}\n```\n")
        }
        if (b.exampleMode == "custom" && b.customExample.isNotBlank()) sb.append("\nCreator's own example (use it):\n```\n${b.customExample}\n```\n")
        val teaser = when {
            b.teaserMode == "custom" && b.customTeaser.isNotBlank() -> b.customTeaser
            else -> lesson?.teaser
        }
        teaser?.let { sb.append("\nNext-lesson teaser text: «$it»\n") }
        if (b.notes.isNotBlank()) sb.append("\nCreator notes: ${b.notes}\n")

        // 4
        h(4, "Mandatory video structure and time budget")
        sb.append(
            """The engine enforces this order; you fill the content. Scene order in the `scenes` array must follow it.

| time | scene type(s) | purpose |
|---|---|---|
| 0–3 s | `hook_predict` (FIRST scene, exactly one) | signature hook «توقّع قبل أن أشغّل»: a tiny snippet + the fixed question «${studio.pyreels.core.model.Scene.HOOK_QUESTION}». Do NOT reveal the answer. |
| 3–10 s | `recap` (second scene) | 5-second recall of the previous lesson |
| 10–40 s | `chat` + one `analogy` | ONE idea only, explained with a real-life analogy, Ahmed asks real beginner questions |
| 40–65 s | `code_type` + `run` | code typed naturally, then step-by-step execution with a visual `trace` |
| ≈45–55 s | `engage_moment` (exactly one) | right after the first small win (first correct output): a warm message, then `bridge` back to the lesson |
| 65–78 s | `reveal` + `common_mistake` | answer to the hook + one common beginner error shown calmly with its fix |
| 78–90 s | `key_sentence` + `teaser` (LAST scene) | sentence of the day + teaser of the next lesson; a final challenge for the comments |

Approximate durations the engine uses: chat message ≈ 2.5–5 s (typing indicator + reading), analogy ≈ 4–6 s, code_type ≈ 0.05 s per character + 1.4 s, run ≈ 1.25 s per trace step + output, engage_moment ≈ 7 s, reveal ≈ 4–6 s, common_mistake ≈ 9–12 s, key_sentence ≈ 4.5 s, teaser ≈ 5–7 s.
Place `engage_moment` so that the scenes before it sum to ≈ 45–50 s.
""",
        )

        // 5
        h(5, "Cast sheet")
        val cast = listOf(Personas.AHMED) + b.teachers.map { Personas.forLanguage(it) }
        val ahmedLevel = SeriesMemory.ahmedLevel(input.history.size)
        cast.forEach { p ->
            sb.append("### ${p.nameAr} (`${p.id}`) — ${if (p.id == "ahmed") "learner" else "teacher"}\n")
            sb.append("- Personality: ${p.personality}\n- Speech style: ${p.style}\n")
            sb.append("- Do: ${p.dos.joinToString("؛ ")}\n- Don't: ${p.donts.joinToString("؛ ")}\n")
            sb.append("- Sample lines: ${p.samples.joinToString(" / ") { "«$it»" }}\n")
            if (p.id == "ahmed") sb.append("- Current level ($ahmedLevel/4): ${SeriesMemory.ahmedLevelDescription(ahmedLevel)}\n")
            sb.append("\n")
        }
        if (b.teachers.size > 1) sb.append("Several teachers: they may react to each other with light, friendly rivalry and show the same idea in their own syntax for comparison. Never mocking, never aggressive.\n")

        // 6
        h(6, "Pedagogy rules")
        sb.append(
            """- **One lesson = one idea = one small challenge.** `meta.lesson.concept` holds exactly ONE concept.
- **Analogy first, syntax second.** The `analogy` card comes before the code.
- **Visual execution trace:** in `run`, give one `trace` step per executed line (with `vars` holding the variables' values after that line; add `iteration` inside loops and `stack` for function calls; put printed text in `out` on the step that prints it).
- **Mistakes are material:** the `common_mistake` uses the REAL interpreter message, a calm Arabic explanation and the fix. Never shame Ahmed.
- **Recap** the previous lesson in one short sentence; **teaser** the next one.
- **Sentence of the day:** one rule, ≤ 10 words, easy to remember.
- **Challenge:** the last chat message (`"challenge": true`) or `teaser.challenge` asks a tiny question to answer in the comments.
- Ahmed asks; teachers answer patiently. Ahmed never already knows the new concept.
""",
        )
        if (b.includeMistake) {
            val errs = ContentRepository.errors.relevant(b.lessonId, curriculum)
            if (errs.isNotEmpty()) {
                sb.append("\n**Errors library (pick ONE for `common_mistake`; copy `error` text exactly, set `libraryId`):**\n\n")
                errs.forEach { e ->
                    sb.append("- `${e.id}` — code: `${e.snippet.replace("\n", "⏎")}` → error: `${e.message}` → fix: `${e.fix.replace("\n", "⏎")}`")
                    e.fixOutput?.let { sb.append(" (fix output: `${it.replace("\n", "⏎")}`)") }
                    sb.append(" — ${e.explain}\n")
                }
            }
        } else sb.append("\nThe creator chose NOT to include a common mistake: omit `common_mistake`.\n")

        // 7
        h(7, "Language rules")
        sb.append(
            when (b.languageStyle) {
                "dialect" -> "- Write in a **light, widely understood Arabic dialect** (close to MSA, no slang that only one country understands).\n"
                "english" -> "- Write all chat text in **simple English**; keep cast names in Arabic only if natural. `meta.language` = `en`.\n"
                else -> "- Write in **simplified Modern Standard Arabic** (فصحى مبسّطة): short, warm, clear.\n"
            },
        )
        sb.append(
            """- Short sentences (one idea per bubble). No filler, no long introductions.
- Code identifiers, keywords and output stay in English inside code; Arabic only in strings/comments if useful.
- Inline code inside chat text goes between backticks, e.g. `x = 5`.
- No emojis in code; at most one gentle emoji in a few chat messages.
- Tone: ${Brief.TONES[b.tone]}; humor level ${b.humor}/5 (${if (b.humor >= 3) "light jokes are welcome, never at Ahmed's expense" else "mostly calm, a smile here and there"}).
""",
        )

        // 8
        h(8, "Output contract")
        if (input.weekly != null) {
            sb.append("Return ONE JSON object: `{ \"schema\": \"pyreels/1\", \"batch\": [ scenario1, …, scenario${input.weekly.size} ] }`. Each item follows the schema below.\n\n")
        } else sb.append("Return ONE JSON object that follows this JSON Schema exactly.\n\n")
        sb.append("**Return JSON only — no markdown fences, no commentary, no explanations before or after.**\n\n")
        sb.append("JSON Schema (draft 2020-12):\n\n```json\n").append(Resources.schemaText.trim()).append("\n```\n\n")
        sb.append("One complete valid example (a different lesson — do not copy its content):\n\n```json\n")
        sb.append(Resources.text("samples/02-variables.pyreels.json").trim()).append("\n```\n")

        // 9
        h(9, "Self-check (run silently before answering)")
        sb.append(
            """- [ ] Valid JSON, matches the schema, `schema` = `pyreels/1`.
- [ ] First scene `hook_predict`, second `recap`, last `teaser`; exactly one `engage_moment`, one `reveal`, one `key_sentence`.
- [ ] Exactly one concept; the hook's answer is revealed only in `reveal`.
- [ ] Estimated total ≈ ${b.targetSeconds} s (± 10 %); the scenes before `engage_moment` sum to ≈ 45–50 s.
- [ ] Every bubble ≤ ${Limits.MAX_LINES_PER_BUBBLE} lines of ≤ ${Limits.MAX_CHARS_PER_LINE} characters; code lines ≤ ${Limits.MAX_CODE_LINE_CHARS} characters.
- [ ] Text is safe-zone friendly: short lines, nothing that depends on screen edges.
- [ ] Every `from` id exists in `cast`; every `sfx` id is in the allowed list; every trace `line` exists in the code.
- [ ] `run.output` is exactly what the code prints; errors are copied from the errors library.
- [ ] `key_sentence` ≤ 10 words; a challenge for the comments exists.
""",
        )

        // 10
        h(10, "Repair note")
        sb.append(
            "The creator will validate your JSON inside the app. If it is invalid, they will send you a **repair prompt** listing each problem with its exact location " +
                "(e.g. «المشهد 7 (chat) ← النص (text): النص طويل جدًا»). When that happens, return the full corrected JSON only, changing nothing else.\n",
        )

        // 11
        h(11, "Series context")
        sb.append("Ahmed's current level: $ahmedLevel/4 — ${SeriesMemory.ahmedLevelDescription(ahmedLevel)}\n\n")
        sb.append("Earlier episodes (Ahmed already knows these; never re-explain them, but you may build on them):\n\n")
        sb.append(SeriesMemory.summary(input.history)).append("\n")
        SeriesMemory.recapFor(input.history)?.let { sb.append("\nSuggested recap text: «$it»\n") }
        sb.append("\nSuggested first question from Ahmed: «${SeriesMemory.suggestedQuestion(ahmedLevel, topic, input.history.lastOrNull()?.title)}»\n")
        input.weekly?.let { week ->
            sb.append("\n### Weekly batch contract\n\n")
            sb.append("Write ${week.size} episodes in this exact order:\n\n")
            week.forEachIndexed { i, l -> sb.append("${i + 1}. `${l.id}` — ${l.title} (concept `${l.concept}`): ${l.summary}\n") }
            sb.append(
                """
- Episode N's `teaser.text` announces episode N+1, and episode N+1's `recap.text` recalls episode N (they must match in meaning).
- Ahmed's level grows across the week (his questions get a little more mature each episode).
- No repeated common mistake and no repeated analogy across the ${week.size} episodes.
- `meta.series.episode` increases by 1 each episode${if (input.history.isNotEmpty()) ", starting at ${input.history.maxOf { it.episode } + 1}" else ", starting at 1"}.
""",
            )
        }

        // 12
        h(12, "Spoken-text rule")
        sb.append(
            """When `say` is true, the app reads the scene's text with TTS after converting code to natural Arabic speech using built-in rules, for example:
`x = 5` → «إكس يساوي خمسة»، `x == 5` → «إكس يطابق خمسة»، `print(...)` → «دالة الطباعة»، `for i in range(3)` → «لكل آي في المدى من صفر إلى ثلاثة».
Set `"speakCode": true` on scenes whose text contains code. Write a `spoken` override **only** when these default reading rules would be wrong. Pick error texts from the errors library above; never invent interpreter messages.
""",
        )
        return sb.toString()
    }

    /** A prompt that returns validation problems to the AI so it can fix its JSON. */
    fun repairPrompt(originalJson: String, problems: List<Problem>): String = buildString {
        append("# Repair request — PyReels Studio scenario (pyreels/1)\n\n")
        append("The JSON you wrote was checked by the app and has the problems below. ")
        append("Fix ONLY these problems, keep everything else identical, and **return the full corrected JSON only — no markdown fences, no commentary**.\n\n")
        append("## Problems\n\n")
        problems.forEachIndexed { i, p ->
            append("${i + 1}. [${p.severity}] ")
            if (p.where.isNotEmpty()) append("**${p.where}** — ")
            append(p.message)
            p.fix?.let { append(" (suggested: $it)") }
            append("\n")
        }
        append("\n## Rules reminder\n\n")
        append("- Scene order: hook_predict first, recap second, teaser last; exactly one engage_moment, reveal and key_sentence.\n")
        append("- Bubbles ≤ ${Limits.MAX_LINES_PER_BUBBLE} lines × ${Limits.MAX_CHARS_PER_LINE} chars; key_sentence ≤ 10 words; total ≈ 90 s.\n")
        append("- Allowed SFX: ${SfxIds.ALL.joinToString(", ")}.\n\n")
        append("## Original JSON\n\n```json\n").append(originalJson.trim()).append("\n```\n\n")
        append("## JSON Schema\n\n```json\n").append(Resources.schemaText.trim()).append("\n```\n")
    }

    private data class Row(val t: String, val p: String, val r: String, val o: String)

    private val sceneTable = listOf(
        Row("hook_predict", "signature 3-s hook", "code", "language, question (keep default), holdMs"),
        Row("recap", "previous lesson in one sentence", "text", ""),
        Row("chat", "one chat message", "from, text", "code (short snippet card), reactions [heart, like, laugh, wow, clap], challenge"),
        Row("analogy", "real-life analogy card with labeled boxes", "title", "items [{label, value}] (≤4), from, text"),
        Row("code_type", "code typed in the editor", "code", "language, typing (natural/steady/instant), focusLines, typo, caption"),
        Row("run", "execution with visual trace + terminal", "— (uses previous code_type's code)", "language, exec (real/simulated), code, trace, output, error, caption"),
        Row("engage_moment", "gentle like/follow/share moment", "text", "from, actions [like, follow, share], bridge"),
        Row("reveal", "answer to the hook", "answer, text", "from"),
        Row("common_mistake", "one beginner error + live fix", "code, error, explain, fix", "language, fixOutput, libraryId, from"),
        Row("key_sentence", "sentence of the day (≤10 words)", "text", ""),
        Row("teaser", "next lesson teaser (last)", "text", "challenge"),
    )
}
